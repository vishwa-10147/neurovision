"""Atomic, versioned local storage for external runs (ADR 0013).

Each run is one JSON file holding its metadata and bounded replay history,
written the same way as projects (ADR 0012): to a temporary file, then
os.replace. Write tokens are never stored, so a reloaded run is read-only.
"""

import json
import os
import threading
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter, ValidationError

from app.schemas.events import CommandKind, TrainingEvent
from app.schemas.runs import RunStatus

RUN_SCHEMA_VERSION = 1
# Events worth replaying after a restart. Commands are left out: no script
# can apply them any more.
STORED_EVENTS = {
    "training.started",
    "training.step",
    "run.alert",
    "training.completed",
    "training.cancelled",
    "training.failed",
}

_events_adapter: TypeAdapter[list[TrainingEvent]] = TypeAdapter(list[TrainingEvent])


class StoredRun(BaseModel):
    schema_version: int
    run_id: str
    name: str
    model_id: str | None
    status: RunStatus
    total_epochs: int
    epoch: int
    step: int | None
    steps_logged: int
    created_at: float
    last_event_at: float
    controls: list[CommandKind]
    learning_rate: float | None
    alerts: int
    events: list[dict[str, Any]]


class RunStore:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()

    def save(self, run: StoredRun) -> None:
        path = self._path(run.run_id)
        temporary = path.with_suffix(".tmp")
        encoded = json.dumps(run.model_dump(mode="json"), separators=(",", ":"))
        with self._lock:
            temporary.write_text(encoded, encoding="utf-8")
            os.replace(temporary, path)

    def load_all(self) -> list[StoredRun]:
        """Every readable run, oldest first; unreadable files are skipped."""
        runs: list[StoredRun] = []
        for path in self.root.glob("run_*.json"):
            try:
                run = StoredRun.model_validate_json(path.read_bytes())
                if run.schema_version != RUN_SCHEMA_VERSION:
                    continue
                # Replayed events must be as valid as live ones.
                _events_adapter.validate_python(run.events)
            except (OSError, ValueError, ValidationError):
                continue
            if path.stem == run.run_id:
                runs.append(run)
        return sorted(runs, key=lambda run: run.created_at)

    def delete(self, run_id: str) -> None:
        with self._lock:
            self._path(run_id).unlink(missing_ok=True)

    def _path(self, run_id: str) -> Path:
        # Run IDs are generated by the server; this check keeps direct callers
        # inside the configured directory.
        if not run_id.startswith("run_") or Path(run_id).name != run_id:
            raise ValueError(f"Invalid run id '{run_id}'.")
        return self.root / f"{run_id}.json"
